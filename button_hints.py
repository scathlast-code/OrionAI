def hint(data):
    """Підпис для кнопки за її даними (найдовший збіг), або ""."""
    if not data:
        return ""
    best = ""
    for k in H:
        if data.startswith(k) and len(k) > len(best) and (len(data) == len(k) or k.endswith((":", "_")) or data[len(k)] in ":_"):
            best = k
    return H.get(best, "")


def for_rows(rows):
    """Для кожного ряду: один спільний підпис (рядок) або список підписів для кожної кнопки."""
    out = []
    for row in rows or []:
        hs = [hint(d) for _, d in row]
        if len(row) > 1 and hs[0] and all(h == hs[0] for h in hs):
            out.append(hs[0])
        else:
            out.append(hs)
    return out
