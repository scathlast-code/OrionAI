def short(key):
    """Кілька слів під плиткою в застосунку (повне пояснення — в «❔ Що це» / ⓘ)."""
    return TILE.get(key) or ""


def text(key, title, esc=lambda s: s):
    """Повне пояснення для екрана «❔ Що це» (HTML бота)."""
    e = E.get(key)
    if not e:
        return ""
    body = "\n\n".join(f"<b>{lab}</b>\n{esc(e[k])}" for k, lab in PARTS if e.get(k))
